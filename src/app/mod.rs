//! 装配层：把索引、检索、触发、回传、界面缝到一起。
//!
//! 三块的分工是刻意的：
//! - [`state`] 持有唯一的可变状态（面板是否打开、过滤串、选中项……）；
//! - [`event`] 定义跨线程消息，是 tap / IPC / 窗口进入 UI 线程的唯一通道；
//! - [`scheduler`] 是唯一消费事件的地方，所有副作用（开窗、关窗、展开）都在它的
//!   单线程循环里按固定顺序执行。
//!
//! 之所以收得这么紧：面板的关闭顺序、吞键的开关、触发符的回删三者互相牵制，
//! 一旦允许某处"顺手"改状态，就会出现"窗口关了但 tap 还在吞键"这类问题。

pub mod event;
pub mod scheduler;
pub mod state;

pub use state::AppState;
